#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo "==> Building bitchat with SwiftPM..."
swift build -c debug

BUILD_DIR="$REPO_ROOT/.build/arm64-apple-macosx/debug"
APP_BUNDLE="$REPO_ROOT/SwiftRescue.app"
CONTENTS="$APP_BUNDLE/Contents"
MACOS_DIR="$CONTENTS/MacOS"
RESOURCES_DIR="$CONTENTS/Resources"

echo "==> Preparing macOS App Bundle at $APP_BUNDLE..."
mkdir -p "$MACOS_DIR"
mkdir -p "$RESOURCES_DIR"

# Copy binary
cp "$BUILD_DIR/bitchat" "$MACOS_DIR/bitchat"
chmod +x "$MACOS_DIR/bitchat"

# Copy resources bundle if generated by SwiftPM
if [ -d "$BUILD_DIR/bitchat_bitchat.bundle" ]; then
    cp -R "$BUILD_DIR/bitchat_bitchat.bundle" "$RESOURCES_DIR/"
fi

# Copy web frontend assets
if [ -d "$REPO_ROOT/web_dist" ]; then
    echo "==> Bundling React Tactical Frontend into App Bundle..."
    mkdir -p "$RESOURCES_DIR/web"
    cp -R "$REPO_ROOT/web_dist/"* "$RESOURCES_DIR/web/"
fi

# Create Info.plist with bundle identifiers and permissions
cat << 'EOF' > "$CONTENTS/Info.plist"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleDisplayName</key>
	<string>SwiftRescue</string>
	<key>CFBundleExecutable</key>
	<string>bitchat</string>
	<key>CFBundleIdentifier</key>
	<string>org.swiftrescue.macos</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>SwiftRescue</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>1.8.0</string>
	<key>CFBundleVersion</key>
	<string>1</string>
	<key>LSApplicationCategoryType</key>
	<string>public.app-category.social-networking</string>
	<key>LSMinimumSystemVersion</key>
	<string>13.0</string>
	<key>NSBluetoothAlwaysUsageDescription</key>
	<string>bitchat uses Bluetooth to create a secure mesh network for chatting with nearby users.</string>
	<key>NSBluetoothPeripheralUsageDescription</key>
	<string>bitchat uses Bluetooth to create a secure mesh network for chatting with nearby users.</string>
	<key>NSPrincipalClass</key>
	<string>NSApplication</string>
	<key>NSSupportsAutomaticTermination</key>
	<false/>
	<key>NSSupportsSuddenTermination</key>
	<false/>
	<key>LSUIElement</key>
	<false/>
	<key>CFBundleURLTypes</key>
	<array>
		<dict>
			<key>CFBundleURLSchemes</key>
			<array>
				<string>bitchat</string>
			</array>
		</dict>
	</array>
</dict>
</plist>
EOF

# Ad-hoc code sign so macOS recognizes entitlements and doesn't trigger security traps
echo "==> Code signing app bundle (ad-hoc)..."
codesign --force --deep -s - "$APP_BUNDLE" 2>/dev/null || true

# Close existing instance if running
echo "==> Closing any previous SwiftRescue instances..."
pkill -f "SwiftRescue\.app/Contents/MacOS/bitchat" 2>/dev/null || true
pkill -f "bitchat\.app/Contents/MacOS/bitchat" 2>/dev/null || true
sleep 1

# Launch the app
echo "==> Launching SwiftRescue.app..."
open "$APP_BUNDLE"

echo "==> SwiftRescue is running! ✅"
